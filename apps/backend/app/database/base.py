"""Declarative base and model conventions.

Conventions for every model:

- Subclass ``Base``. Use SQLAlchemy 2.x typed mappings (``Mapped[...]`` with
  ``mapped_column``).
- Table names are plural snake_case, set explicitly with ``__tablename__``.
- Use ``UUIDPrimaryKeyMixin`` for a random UUID primary key, so identifiers
  are not guessable or enumerable.
- Use ``TimestampMixin`` for ``created_at`` and ``updated_at``.
- ``datetime`` columns are always timezone-aware (``timestamptz``) and
  stored in UTC.
- Constraint and index names follow ``NAMING_CONVENTION``, so Alembic
  migrations are deterministic.
- Register every model module in ``app.models`` so Alembic can see it.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, Uuid, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class for all ORM models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {
        datetime: DateTime(timezone=True),
        uuid.UUID: Uuid(as_uuid=True),
    }


class UUIDPrimaryKeyMixin:
    """Random (version 4) UUID primary key, generated by the application."""

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)


class TimestampMixin:
    """Creation and last-update times, set by the database in UTC."""

    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=func.now()
    )
