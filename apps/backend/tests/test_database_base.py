"""ORM metadata and model convention tests. No database server is needed."""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, String, Table, Uuid
from sqlalchemy.dialects import postgresql
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.schema import CreateTable

import app.models  # noqa: F401
from app.database.base import NAMING_CONVENTION, Base, TimestampMixin, UUIDPrimaryKeyMixin


def test_metadata_uses_naming_convention() -> None:
    assert Base.metadata.naming_convention == {**MetaData().naming_convention, **NAMING_CONVENTION}


def test_no_business_models_exist_yet() -> None:
    # Business models are added by the roadmap phases that build each feature.
    assert Base.metadata.tables == {}


def test_model_conventions() -> None:
    class ConventionBase(Base):
        __abstract__ = True
        metadata = MetaData(naming_convention=NAMING_CONVENTION)

    class Example(UUIDPrimaryKeyMixin, TimestampMixin, ConventionBase):
        __tablename__ = "examples"
        name: Mapped[str] = mapped_column(String(100), unique=True)
        category: Mapped[str] = mapped_column(String(50), index=True)
        seen_at: Mapped[datetime | None]

    table = Example.__table__
    assert isinstance(table, Table)
    assert table.metadata is not Base.metadata  # the shared Base metadata is untouched
    assert "examples" not in Base.metadata.tables

    # UUID primary key generated by the application.
    id_column = table.c.id
    assert id_column.primary_key
    assert isinstance(id_column.type, Uuid)
    assert id_column.default is not None
    assert isinstance(id_column.default.arg(None), uuid.UUID)

    # Every datetime column is timezone-aware.
    for name in ("created_at", "updated_at", "seen_at"):
        column_type = table.c[name].type
        assert isinstance(column_type, DateTime)
        assert column_type.timezone is True
    assert table.c.created_at.server_default is not None
    assert table.c.updated_at.onupdate is not None

    # Constraint and index names follow the naming convention.
    ddl = str(CreateTable(table).compile(dialect=postgresql.dialect()))  # type: ignore[no-untyped-call]
    assert "CONSTRAINT pk_examples PRIMARY KEY" in ddl
    assert "CONSTRAINT uq_examples_name UNIQUE" in ddl
    assert "TIMESTAMP WITH TIME ZONE" in ddl
    assert {index.name for index in table.indexes} == {"ix_examples_category"}
